-- Run this in Supabase SQL Editor for visitor analytics + final messages.
-- Safe to run after the older schema: the new columns are added only if missing.
-- No camera/microphone/video/audio tables are included.

create table if not exists public.visitor_events (
  id bigint generated by default as identity primary key,
  session_id text not null,
  visitor_id text,
  visit_number integer,
  recipient_id text not null,
  recipient_name text,
  nickname text,
  event_type text not null,
  detail jsonb default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.visitor_messages (
  id bigint generated by default as identity primary key,
  session_id text not null,
  visitor_id text,
  visit_number integer,
  recipient_id text not null,
  recipient_name text,
  nickname text,
  message text not null,
  created_at timestamptz not null default now()
);

-- Add the return-visit columns to an already-created project.
alter table public.visitor_events add column if not exists visitor_id text;
alter table public.visitor_events add column if not exists visit_number integer;
alter table public.visitor_messages add column if not exists visitor_id text;
alter table public.visitor_messages add column if not exists visit_number integer;

alter table public.visitor_events enable row level security;
alter table public.visitor_messages enable row level security;

-- Anonymous visitors may INSERT only. They cannot SELECT other visitors' data.
do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='visitor_events' and policyname='anon can insert visitor events') then
    create policy "anon can insert visitor events"
    on public.visitor_events for insert
    to anon with check (true);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='visitor_messages' and policyname='anon can insert visitor messages') then
    create policy "anon can insert visitor messages"
    on public.visitor_messages for insert
    to anon with check (true);
  end if;
end $$;

create index if not exists visitor_events_visitor_visit_idx
on public.visitor_events (visitor_id, visit_number, created_at);

create index if not exists visitor_messages_visitor_visit_idx
on public.visitor_messages (visitor_id, visit_number, created_at);

-- IMPORTANT: Do NOT create a public SELECT policy.
