-- Recipient names are editable from the protected creator dashboard.
create table if not exists public.surprise_recipients (
  recipient_id text primary key,
  name text not null,
  updated_at timestamptz not null default now()
);

alter table public.surprise_recipients enable row level security;

-- The public site needs only the recipient name for the ?to=... link.
drop policy if exists "public can read surprise recipient names" on public.surprise_recipients;
create policy "public can read surprise recipient names"
on public.surprise_recipients
for select
to anon, authenticated
using (true);

create index if not exists surprise_recipients_updated_idx
on public.surprise_recipients (updated_at);

